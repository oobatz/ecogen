// Нормализация: строки → объекты-задачи без type (неиграбельны в этой версии); XP за задачу.
EG.data.levels.forEach(function (lv) {
  lv.playable = lv.tasks.every(function (t) { return typeof t === 'object'; });
  lv.tasks = lv.tasks.map(function (t) { return typeof t === 'string' ? { t: t } : t; });
  lv.tasks.forEach(function (t) { t.xp = 10 + lv.n * 5; });
  lv.xpTotal = lv.tasks.length * (10 + lv.n * 5);
  lv.coins = lv.n * 100;
});
